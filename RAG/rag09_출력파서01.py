# LCEL = LangChain Expression Language
# chain = prompt | model | output_parser

from langchain_openai import ChatOpenAI
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import StrOutputParser
import os
from dotenv import load_dotenv

load_dotenv()

api_key = os.environ["MONOROUTER_API_KEY"].strip()
base_url = "https://monogpt.kr/api/monorouter/v1/"

prompt = PromptTemplate.from_template("{topic}에 대해 쉽게 설명해주세요")

model = ChatOpenAI(
    model_name="gpt-5.6-terra",
    temperature=0,
    api_key=api_key,
    base_url=base_url,
)

output_parser = StrOutputParser()

chain = prompt | model | output_parser

input = {"topic": "양자컴퓨터 학습 원리"}

response = chain.invoke(input)
print(response)
# 양자컴퓨터는 **아주 작은 세계(원자·전자 수준)의 물리 법칙**을 이용해 계산하는 컴퓨터입니다. 일반 컴퓨터와 가장 큰 차이는 정보를 표현하는 방식입니다.

# ## 1. 일반 컴퓨터: 비트(bit)

# 일반 컴퓨터는 정보를 `0` 또는 `1`로 저장합니다.

# - 전등이 꺼짐 = 0
# - 전등이 켜짐 = 1

# 이런 단위를 **비트**라고 합니다.  
# 예를 들어 3비트라면 `000`부터 `111`까지 하나의 상태만 가질 수 있습니다.

# ---

# ## 2. 양자컴퓨터: 큐비트(qubit)

# 양자컴퓨터는 **큐비트**를 사용합니다.

# 큐비트는 측정하기 전까지는 단순히 0 또는 1 중 하나가 아니라,

# > **0과 1의 가능성을 함께 가진 상태**

# 가 될 수 있습니다. 이를 **중첩(superposition)**이라고 합니다.

# 동전을 생각하면 쉽습니다.

# - 바닥에 놓인 동전: 앞면 또는 뒷면 → 일반 비트
# - 공중에서 빙글빙글 도는 동전: 앞면과 뒷면이 아직 정해지지 않음 → 큐비트의 중첩 상태

# 단, 동전을 손으로 잡아 확인하는 순간 앞면 또는 뒷면으로 정해지듯, 큐비트도 **측정하면 0 또는 1 중 하나로 결과가 결정**됩니다.

# ---

# ## 3. 여러 경우를 동시에 다루는 중첩

# 큐비트가 여러 개 있으면 많은 상태를 한 번에 표현할 수 있습니다.

# - 1큐비트: 0, 1의 가능성
# - 2큐비트: 00, 01, 10, 11의 가능성
# - 3큐비트: 8가지 경우의 가능성
# - n큐비트: \(2^n\)가지 경우의 가능성

# 그래서 양자컴퓨터는 특히 경우의 수가 매우 많은 문제에서 강력할 가능성이 있습니다.

# 하지만 이것을 “모든 답을 한 번에 계산해서 바로 알려준다”라고 이해하면 조금 틀립니다.  
# 측정하면 결국 답은 하나만 나오므로, **원하는 답이 나올 확률을 높이도록 계산 과정을 설계해야 합니다.**

# ---

# ## 4. 얽힘: 큐비트끼리 특별하게 연결됨

# 양자컴퓨터의 또 다른 핵심은 **얽힘(entanglement)**입니다.

# 두 큐비트가 얽히면, 각각을 따로 설명하기 어려울 정도로 상태가 연결됩니다.

# 예를 들어 두 큐비트가 얽혀 있을 때:

# - 첫 번째를 측정해서 0이 나오면
# - 두 번째도 특정 규칙에 따라 0 또는 1로 정해집니다.

# 마치 멀리 떨어진 두 개의 상자가 이상하게 연결되어 있어, 하나를 열어보면 다른 하나의 상태와 관계가 즉시 드러나는 것처럼 보입니다.

# 이 얽힘 덕분에 양자컴퓨터는 여러 정보 사이의 관계를 매우 효율적으로 표현하고 처리할 수 있습니다.

# ---

# ## 5. 간섭: 정답은 강화하고 오답은 약화하기

# 양자 알고리즘의 핵심은 **간섭(interference)**입니다.

# 파동은 서로 만나면:

# - 더 커질 수도 있고 → 보강 간섭
# - 서로 사라질 수도 있습니다 → 상쇄 간섭

# 양자컴퓨터는 이 성질을 이용해,

# - 정답에 해당하는 상태의 확률은 높이고
# - 오답에 해당하는 상태의 확률은 낮추도록

# 큐비트를 조작합니다.

# 즉, 양자컴퓨터는 단순히 많은 경우를 펼쳐 놓는 것이 아니라,  
# **간섭을 이용해 정답이 측정될 가능성을 키우는 컴퓨터**라고 볼 수 있습니다.

# ---

# ## 6. 양자 게이트: 큐비트를 조작하는 명령

# 일반 컴퓨터가 AND, OR, NOT 같은 논리 게이트를 사용하듯, 양자컴퓨터는 **양자 게이트**를 사용합니다.

# 대표적으로:

# - **X 게이트**: 0과 1을 뒤집음  
#   - 0 → 1  
#   - 1 → 0
# - **H 게이트**: 큐비트를 중첩 상태로 만듦
# - **CNOT 게이트**: 두 큐비트를 연결해 얽힘을 만드는 데 사용

# 이 게이트들을 특정 순서로 배치한 것을 **양자 회로**라고 합니다.  
# 양자 알고리즘은 결국 “어떤 양자 게이트를 어떤 순서로 적용할 것인가”를 설계하는 일입니다.

# ---

# ## 7. 계산 과정 요약

# 양자컴퓨터의 계산은 보통 이렇게 진행됩니다.

# 1. 큐비트를 0 상태로 준비
# 2. 양자 게이트를 적용해 중첩과 얽힘 생성
# 3. 간섭을 이용해 정답 확률을 높임
# 4. 큐비트를 측정
# 5. 0과 1의 결과를 받아 답을 해석

# 측정 결과에는 확률성이 있으므로, 같은 계산을 여러 번 반복해 결과를 확인하는 경우도 많습니다.

# ---

# ## 8. 어디에 유리한가?

# 양자컴퓨터가 모든 작업에서 일반 컴퓨터보다 빠른 것은 아닙니다. 특히 다음 분야에서 가능성이 큽니다.

# - **암호 해독 및 보안**
# - **신약 개발**: 분자 구조와 화학 반응 시뮬레이션
# - **재료 개발**: 배터리, 초전도체 등
# - **복잡한 최적화**: 배송 경로, 일정 배치, 금융 포트폴리오
# - **대규모 데이터 검색**
# - 일부 **인공지능·머신러닝** 문제

# ---

# ## 9. 아직 어려운 점

# 양자 상태는 매우 약해서 외부 열, 진동, 전자기파 등에 쉽게 영향을 받습니다. 이를 **양자 오류** 또는 **디코히런스**라고 합니다.

# 그래서 현재 양자컴퓨터는 보통 매우 낮은 온도에서 작동하며, 오류를 줄이는 기술이 매우 중요합니다.

