# 문장을 단어 단위로 분리하고, 각 단어에 정수 번호를 부여하는 클래스
from tensorflow.keras.preprocessing.text import Tokenizer
import numpy as np

# 분석할 문장
text1 = "나는 지금 매우 매우 맛있는 김밥을 엄청 많이 많이 먹었다"
text2 = "개똥이는 기관사를 좋아힌다. 말똥이는 잘생겼다. 길동이 매우 매우 매우 더 잘생겼다."

# Tokenizer 객체 생성
token = Tokenizer() # 객체(인스턴스) = 클래스() = 인스턴스 생성

# 문장을 학습시켜 단어 빈도를 세고, 단어별 정수 번호를 부여
token.fit_on_texts([text1, text2]) # 대괄호로 감싸는 이유: fit_on_texts()는 문장들의 리스트를 입력으로 받기 때문

# 단어별 정수 번호 출력
# 빈도가 높은 단어부터 작은 번호가 부여됨
# 빈도가 같으면 문장에 먼저 등장한 단어가 앞 번호를 받음
print(token.word_index)
# {'매우': 1, '많이': 2, '잘생겼다': 3, '나는': 4, '지금': 5, '맛있는': 6, '김밥을': 7, '엄청': 8, '먹었다': 9, '개똥이는': 10, '기관사를': 11, '좋아힌다': 12, '말똥이는': 13, '길동이': 14, '더': 15}

# 단어별 등장 횟수 출력
print(token.word_counts)
# OrderedDict([('나는', 1), ('지금', 1), ('매우', 4), ('맛있는', 1), ('김밥을', 1), ('엄청', 1), ('많이', 2), ('먹었다', 1), ('개똥이는', 1), ('기관사를', 1), ('좋아힌다', 1), ('말똥이는', 1), ('잘생겼다', 2), ('길동이', 1), ('더', 1)])

# 원래 문장을 Tokenizer가 부여한 단어 번호 시퀀스로 변환
# 바깥 리스트는 문장 단위, 안쪽 리스트는 각 문장의 토큰 번호
x = token.texts_to_sequences([text1, text2])
print(x) # [[4, 5, 1, 1, 6, 7, 8, 2, 2, 9], [10, 11, 12, 13, 3, 14, 1, 1, 15, 3]]
x = np.concatenate(x)
print(x) # [ 4  5  1  1  6  7  8  2  2  9 10 11 12 13  3 14  1  1  1 15  3]


